//! The Python package's `__init__.py` (`gen bindings`): every public name of its modules
//! imported by name and listed in `__all__`, so `from fs_inspect import X` names each class,
//! enum and exception, for mypy too.

use std::fmt::Write as _;

/// The names in a generated module's `__all__`.
fn all_of(text: &str) -> Vec<String> {
    let head = "\n__all__ = [\n";
    let Some(i) = text.find(head) else { return Vec::new() };
    text[i + head.len()..]
        .lines()
        .take_while(|l| !l.starts_with(']'))
        .map(|l| l.trim().trim_end_matches(',').trim_matches('"').to_string())
        .filter(|n| !n.is_empty())
        .collect()
}

/// The public names of the stub: its classes, functions and `__version__`.
fn stub_names(stub: &str) -> Vec<String> {
    let mut out: Vec<String> = stub
        .lines()
        .filter_map(|l| l.strip_prefix("class ").or_else(|| l.strip_prefix("def ")))
        .map(|l| l.split([':', '(']).next().unwrap_or("").trim().to_string())
        .filter(|n| !n.is_empty() && !n.starts_with('_'))
        .collect();
    out.push("__version__".to_string());
    out
}

/// `from fs_inspect.<module> import (...)` of `names`, sorted as isort sorts them:
/// constants, classes, then the rest, each ignoring case.
fn import(module: &str, names: &[String]) -> String {
    let mut names = names.to_vec();
    names.sort_by_key(|n| {
        let constant = n.len() > 1 && n.chars().all(|c| c.is_ascii_uppercase() || c == '_' || c.is_ascii_digit());
        let rank = if constant {
            0
        } else if n.starts_with(|c: char| c.is_ascii_uppercase()) {
            1
        } else {
            2
        };
        (rank, n.to_lowercase())
    });
    let one = format!("from fs_inspect.{module} import {}", names.join(", "));
    if one.len() <= 100 {
        return one + "\n";
    }
    let mut s = format!("from fs_inspect.{module} import (\n");
    for n in &names {
        let _ = writeln!(s, "    {n},");
    }
    s.push_str(")\n");
    s
}

const HEAD: &str = r#""""fs-inspect for Python: read the file systems inside disk images, snapshot devices and backups.

Open disks as one set (``DiskSet.open``), list their volumes named as the guest systems
know them (``DiskSet.catalog``), browse a volume's file system (``Volume.browse``: ``Fs``),
read its files (``File``), map and verify its blocks (``Volume.map``, ``Volume.verify``).
Calls that read release the GIL while they run; a caller's ``Source`` is called from
fs-inspect's own threads. ``fs_inspect.aio`` has the same API for asyncio.

The names are the library's: classes, methods and fields alike. An enum is a ``StrEnum``
whose members equal their stable lower-case names (``stat.kind == NodeKind.FILE``); flags
are ``IntFlag``s. A value with variants (``LinkTarget``, ``VolumeState``, ...) has a class
per variant nested in it (``LinkTarget.Symlink``), each with its own fields and a ``kind``,
to take apart with ``match``. Values compare and hash by their fields; options also have
``replace(**changes)``. Each ``ErrorKind`` has its exception, a subclass of
``FsInspectError`` and, where one means the same, of a built-in one (``NotFoundError`` is a
``FileNotFoundError``).

``File``, ``DirCursor``, ``Walker`` and ``ReadAhead`` are context managers; ``Listing``,
``Siblings`` and ``Blocks`` are ``Sequence``s.

Generated by ``cargo xtask gen bindings``: do not edit.
"""

from __future__ import annotations

import collections.abc as _abc

"#;

/// `__init__.py` of the stub and the generated `_kinds.py` and `_errors.py`.
pub fn init(stub: &str, kinds: &str, errors: &str) -> String {
    let modules = [
        ("_errors", all_of(errors)),
        ("_file", vec!["File".to_string()]),
        ("_kinds", all_of(kinds)),
        ("_native", stub_names(stub)),
        ("_source", vec!["Source".to_string()]),
    ];
    let mut s = String::from(HEAD);
    let mut all: Vec<String> = Vec::new();
    for (m, names) in &modules {
        s.push_str(&import(m, names));
        all.extend(names.iter().cloned());
    }
    all.sort();
    all.dedup();
    s.push_str("\n__all__ = [\n");
    for n in &all {
        let _ = writeln!(s, "    \"{n}\",");
    }
    s.push_str("]\n");
    s.push_str(SEQUENCES);
    s
}

/// What `__init__.py` does after its imports: the native sequences registered as `Sequence`s.
const SEQUENCES: &str =
    "\n_abc.Sequence.register(Blocks)\n_abc.Sequence.register(Listing)\n_abc.Sequence.register(Siblings)\n";
