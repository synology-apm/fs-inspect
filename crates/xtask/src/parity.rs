//! `lint`'s parity check, both ways:
//!
//! - every public item of the facade (`api/fs-inspect.txt`) is in the Python binding
//!   (`_native.pyi`) and the C API (`fs_inspect.h`), under the name `api/parity.toml` gives or
//!   the default one, unless the manifest says why it is Rust's only (what is missing);
//! - every class member of the binding and every function of the header is one of them (what
//!   is left over).
//!
//! The facade's items come from the committed public API listing (which `lint` keeps current),
//! the binding's from its type stub (which its stubtest keeps true to the module), the C API's
//! from the committed header (which `lint` keeps current): no build, no Python, no compiler.
//!
//! What is checked:
//! - each type with an inherent method or a public field (a trait's methods, and those an enum
//!   gets from the name registry, are not: the registry generates them);
//! - each inherent method and public field of such a type; an options type's `with_x` is its
//!   field `x`;
//! - each free function.
//!
//! Default names: a type's Python class has its Rust name, and a method or field has its Rust
//! name in the class (a method, a property, or the constructor for `new`). A handle's C function
//! is `{c}_{method}`, and a field is the same field of `c-struct`.
//!
//! A C name `"- why"` (or `"-"`) means the item is not bound there, for that reason; a type's
//! `c = "- why"` covers its items. `pending` marks what a binding does not have yet (`py`,
//! `c`), as does a leftover's reason `TODO`. `lint` counts them, and passes with them until the
//! manifest says `strict = true`; `gen parity` sets them ([`update_text`]), and `lint` fails when
//! the manifest is not what it writes.

