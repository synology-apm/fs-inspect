/// Methods every enum of the name registry has (`named_enum!`, `tagged_enum!`): generated in
/// each binding from the registry, not listed.
const REGISTRY_METHODS: [&str; 7] = ["as_str", "from_name", "code", "from_code", "kind", "doc", "from_str"];

/// A Rust item the bindings must have: a method or field of a type, or a free function.
#[derive(Debug, Clone, PartialEq, Eq, PartialOrd, Ord)]
pub struct Item {
    /// The type's path (`fs_inspect::fs::FsHandle`), or the function's module.
    pub owner: String,
    pub name: String,
    pub field: bool,
}

/// The facade as the listing shows it.
#[derive(Debug, Default)]
pub struct Rust {
    /// Types with something to bind: path → (is an enum).
    pub types: BTreeMap<String, bool>,
    pub items: BTreeSet<Item>,
}

/// Parse the public API listing.
pub fn rust_items(api: &str) -> Rust {
    let mut r = Rust::default();
    let mut enums = BTreeSet::new();
    let mut traits = BTreeSet::new();
    let mut types = BTreeSet::new();
    let mut mods = BTreeSet::new();
    for line in api.lines() {
        let l = strip_attrs(line);
        if let Some(p) = l.strip_prefix("pub enum ") {
            enums.insert(path_of(p));
            types.insert(path_of(p));
        } else if let Some(p) = l.strip_prefix("pub struct ") {
            types.insert(path_of(p));
        } else if let Some(p) = l.strip_prefix("pub trait ") {
            traits.insert(path_of(p));
        } else if let Some(p) = l.strip_prefix("pub mod ") {
            mods.insert(path_of(p));
        }
    }
    // A type the listing shows again where it is re-exported (`a::T` for `a::m::T`): the
    // defining path only.
    let all = types.clone();
    types.retain(|p: &String| {
        let (parent, name) = p.rsplit_once("::").unwrap_or(("", p));
        !all.iter().any(|q| {
            q != p && q.rsplit_once("::").is_some_and(|(qp, qn)| qn == name && qp.starts_with(&format!("{parent}::")))
        })
    });
    // `impl Type` (inherent) or `impl Trait for Type` (skipped) heads the lines after it.
    let mut inherent: Option<String> = None;
    for line in api.lines() {
        let l = strip_attrs(line);
        if let Some(rest) = l.strip_prefix("impl") {
            let rest = skip_generics(rest.trim_start());
            inherent = (!rest.contains(" for ")).then(|| path_of(rest)).filter(|t| types.contains(t));
            continue;
        }
        if l.starts_with("pub struct ") || l.starts_with("pub enum ") || l.starts_with("pub trait ") {
            inherent = None;
            continue;
        }
        let f = ["pub fn ", "pub const fn ", "pub async fn ", "pub unsafe fn ", "pub const unsafe fn "];
        if let Some(rest) = f.iter().find_map(|p| l.strip_prefix(p)) {
            let path = path_of(rest);
            let Some((owner, name)) = path.rsplit_once("::") else { continue };
            if traits.contains(owner) {
                continue;
            }
            if types.contains(owner) {
                if inherent.as_deref() != Some(owner) {
                    continue;
                }
                if enums.contains(owner) && REGISTRY_METHODS.contains(&name) {
                    continue;
                }
                let (name, field) = match name.strip_prefix("with_") {
                    Some(f) => (f, true),
                    None => (name, false),
                };
                r.items.insert(Item { owner: owner.into(), name: name.into(), field });
                r.types.insert(owner.into(), enums.contains(owner));
            } else if mods.contains(owner) || owner.starts_with("fs_inspect") {
                r.items.insert(Item { owner: owner.into(), name: name.into(), field: false });
            }
            continue;
        }
        // A field: `pub path::Type::field: T`.
        if let Some(rest) = l.strip_prefix("pub ")
            && let Some((path, _)) = rest.split_once(": ")
            && let Some((owner, name)) = path.rsplit_once("::")
            && types.contains(owner)
            && !name.chars().next().is_some_and(|c| c.is_ascii_digit())
        {
            r.items.insert(Item { owner: owner.into(), name: name.into(), field: true });
            r.types.insert(owner.into(), enums.contains(owner));
        }
    }
    r
}

fn strip_attrs(line: &str) -> &str {
    let mut l = line.trim();
    while l.starts_with("#[") {
        match l.find("] ") {
            Some(i) => l = l[i + 2..].trim_start(),
            None => return "",
        }
    }
    l
}

fn skip_generics(s: &str) -> &str {
    if !s.starts_with('<') {
        return s;
    }
    let mut depth = 0;
    for (i, c) in s.char_indices() {
        match c {
            '<' => depth += 1,
            '>' => {
                depth -= 1;
                if depth == 0 {
                    return s[i + 1..].trim_start();
                }
            }
            _ => {}
        }
    }
    s
}

/// The path at the start of `s`, without its generic arguments (`a::T<'_>::f` is `a::T::f`).
fn path_of(s: &str) -> String {
    let mut out = String::new();
    let mut depth = 0;
    for c in s.chars() {
        match c {
            '<' => depth += 1,
            '>' if depth > 0 => depth -= 1,
            _ if depth > 0 => {}
            c if c.is_alphanumeric() || c == '_' || c == ':' => out.push(c),
            _ => break,
        }
    }
    out.trim_end_matches(':').to_string()
}

/// The binding's classes and their members (methods, properties); `""` is the module.
pub fn py_members(pyi: &str, kinds: &str) -> BTreeMap<String, BTreeSet<String>> {
    let mut out: BTreeMap<String, BTreeSet<String>> = BTreeMap::new();
    for text in [pyi, kinds] {
        let mut class: Option<String> = None;
        // Inside a docstring of several lines: its lines are text, not members.
        let mut in_doc = false;
        for line in text.lines() {
            let opens_or_closes = line.matches("\"\"\"").count() % 2 == 1;
            if in_doc {
                in_doc = !opens_or_closes;
                continue;
            }
            in_doc = opens_or_closes;
            if let Some(rest) = line.strip_prefix("class ") {
                // A private class (`_File`, the native half of a Python one) binds nothing.
                let name = ident(rest);
                class = (!name.starts_with('_')).then(|| {
                    out.entry(name.clone()).or_default();
                    name
                });
            } else if line.starts_with("    class ") {
                // A variant's class, nested in its enum's: the enum's variants are not items.
            } else if let Some(def) = line.strip_prefix("def ") {
                out.entry(String::new()).or_default().insert(ident(def));
                class = None;
            } else if !line.starts_with(' ') && !line.is_empty() && !line.starts_with('@') && !line.starts_with('#') {
                class = None;
            } else if let (Some(c), Some(def)) = (&class, line.strip_prefix("    def ")) {
                out.entry(c.clone()).or_default().insert(ident(def));
            } else if let Some(c) = &class
                && let Some(attr) = line.strip_prefix("    ")
                && !attr.starts_with(' ')
                && attr.contains(':')
                && !attr.starts_with("def ")
            {
                // A class attribute: `name: type` (or `NAME = ...`).
                let name = ident(attr);
                if !name.is_empty() {
                    out.entry(c.clone()).or_default().insert(name);
                }
            }
        }
    }
    out
}

fn ident(s: &str) -> String {
    s.chars().take_while(|c| c.is_alphanumeric() || *c == '_').collect()
}

/// The header's functions and each struct's fields.
#[derive(Debug, Default)]
pub struct Header {
    pub functions: BTreeSet<String>,
    pub structs: BTreeMap<String, BTreeSet<String>>,
}

pub fn c_items(h: &str) -> Header {
    let mut out = Header::default();
    let mut current: Option<String> = None;
    let mut depth = 0i32;
    for line in h.lines() {
        let t = line.trim();
        if t.starts_with("//") || t.is_empty() {
            continue;
        }
        if let Some(rest) = t.strip_prefix("typedef struct ")
            && t.ends_with('{')
        {
            let name = ident(rest);
            out.structs.entry(name.clone()).or_default();
            current = Some(name);
            continue;
        }
        if let Some(s) = &current {
            if t.starts_with('}') {
                current = None;
                continue;
            }
            if depth > 0 {
                depth += paren_balance(t);
                continue;
            }
            if let Some(i) = t.find("(*") {
                out.structs.entry(s.clone()).or_default().insert(ident(&t[i + 2..]));
                depth = paren_balance(t);
                continue;
            }
            if let Some(decl) = t.strip_suffix(';') {
                let decl = decl.split('[').next().unwrap_or(decl);
                if let Some(name) = decl.rsplit([' ', '*']).next() {
                    out.structs.entry(s.clone()).or_default().insert(name.to_string());
                }
            }
            continue;
        }
        if line.starts_with(' ') || t.starts_with("typedef") || t.starts_with('#') {
            continue;
        }
        // `ret fs_inspect_name(`: the first name followed by its parameters.
        for (i, _) in t.match_indices("fs_inspect_") {
            let name = ident(&t[i..]);
            if t[i + name.len()..].starts_with('(') {
                out.functions.insert(name);
                break;
            }
        }
    }
    out
}

fn paren_balance(s: &str) -> i32 {
    s.chars().map(|c| i32::from(c == '(') - i32::from(c == ')')).sum()
}

/// What the manifest says of one item or type.
#[derive(Debug, Default, Clone)]
struct Says {
    py: Option<String>,
    c: Option<String>,
    c_struct: Option<String>,
    rust_only: Option<String>,
    pending_py: bool,
    pending_c: bool,
}

fn says(v: Option<&Value>) -> Result<Says, String> {
    let Some(v) = v else { return Ok(Says::default()) };
    let t = v.as_table().ok_or("an entry is a table")?;
    let s = |k: &str| t.get(k).and_then(Value::as_str).map(str::to_string);
    let pending: Vec<&str> =
        t.get("pending").and_then(Value::as_array).map_or(Vec::new(), |a| a.iter().filter_map(Value::as_str).collect());
    for k in t.keys() {
        if !["py", "c", "c-struct", "rust-only", "pending", "items"].contains(&k.as_str()) {
            return Err(format!("unknown key {k:?}"));
        }
    }
    Ok(Says {
        py: s("py"),
        c: s("c"),
        c_struct: s("c-struct"),
        rust_only: s("rust-only"),
        pending_py: pending.contains(&"py"),
        pending_c: pending.contains(&"c"),
    })
}

/// Where a Rust item stands in one binding.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum Is {
    There,
    Missing,
    /// Not bound there, as the manifest says (`-`), or nothing to bind (an enum's C side: the
    /// registry's constants).
    NotBound,
}

/// A Rust type, item or free function and where it stands.
#[derive(Debug)]
struct Row {
    /// `(type, "")` for a type itself, `(type, item)`, or `("", function path)`.
    key: (String, String),
    /// The type's Python class (empty for a function).
    class: String,
    says: Says,
    /// The Python class or member, the C function or field, as looked for.
    py_name: String,
    c_name: String,
    py: Is,
    c: Is,
}

/// The facade against both bindings, the manifest's names applied, its pending marks not.
#[derive(Debug, Default)]
struct Eval {
    rows: Vec<Row>,
    /// What binds no Rust item: `Class`, `Class.member`, `function`; C functions.
    leftover_py: BTreeSet<String>,
    leftover_c: BTreeSet<String>,
    /// What the manifest names that is not there.
    stale: Vec<String>,
    manifest: Table,
}

fn evaluate(api: &str, pyi: &str, kinds: &str, header: &str, manifest: &str) -> Result<Eval, String> {
    let rust = rust_items(api);
    let py = py_members(pyi, kinds);
    let c = c_items(header);
    let m: Table = manifest.parse().map_err(|e| format!("{MANIFEST}: {e}"))?;
    let empty = Table::new();
    let tbl = |k: &str| m.get(k).and_then(Value::as_table).unwrap_or(&empty);
    let (modules, types, functions) = (tbl("modules"), tbl("types"), tbl("functions"));
    let mut e = Eval::default();
    let mut claimed_py: BTreeSet<(String, String)> = BTreeSet::new();
    let mut claimed_c: BTreeSet<String> = BTreeSet::new();
    let rust_only_module = |p: &str| modules.keys().any(|m| p == m || p.starts_with(&format!("{m}::")));

    for (ty, &is_enum) in &rust.types {
        if rust_only_module(ty) {
            continue;
        }
        let entry = types.get(ty);
        let t = says(entry).map_err(|x| format!("{MANIFEST}: types.{ty:?}: {x}"))?;
        let short = ty.rsplit("::").next().unwrap_or(ty);
        let class = t.py.clone().unwrap_or_else(|| short.to_string());
        let class_is = if t.rust_only.is_some() {
            Is::NotBound
        } else if py.contains_key(&class) {
            claimed_py.insert((class.clone(), String::new()));
            Is::There
        } else {
            Is::Missing
        };
        e.rows.push(Row {
            key: (ty.clone(), String::new()),
            class: class.clone(),
            says: t.clone(),
            py_name: class.clone(),
            c_name: String::new(),
            py: class_is,
            c: Is::NotBound,
        });
        let items = entry.and_then(|v| v.get("items")).and_then(Value::as_table).unwrap_or(&empty);
        for k in items.keys() {
            if !rust.items.iter().any(|i| &i.owner == ty && &i.name == k) {
                e.stale.push(format!("{MANIFEST}: {ty}.{k}: no such item"));
            }
        }
        if t.rust_only.is_some() {
            continue;
        }
        for it in rust.items.iter().filter(|i| &i.owner == ty) {
            let s = says(items.get(&it.name)).map_err(|x| format!("{MANIFEST}: {ty}.{}: {x}", it.name))?;
            let py_name =
                s.py.clone().unwrap_or_else(|| if it.name == "new" { "__init__".into() } else { it.name.clone() });
            let py_is = if s.rust_only.is_some() || py_name == "-" {
                Is::NotBound
            } else if py
                .get(&class)
                .is_some_and(|m| m.contains(&py_name) || (py_name == "__init__" && m.contains("__new__")))
            {
                claimed_py.insert((class.clone(), py_name.clone()));
                Is::There
            } else {
                Is::Missing
            };
            // C: a field of the type's struct, or a function.
            let c_name = match (&s.c, it.field, &t.c_struct, &t.c) {
                (Some(n), ..) => n.clone(),
                // A type not bound in C (`c = "- why"`): nor are its items.
                (None, _, _, Some(p)) if not_bound(p) => p.clone(),
                (None, true, Some(_), _) => it.name.clone(),
                (None, false, _, Some(p)) => format!("{p}_{}", it.name),
                _ => String::new(),
            };
            let c_is = if s.rust_only.is_some() || not_bound(&c_name) || (is_enum && s.c.is_none()) {
                Is::NotBound
            } else if c_name.starts_with("fs_inspect_") {
                if c.functions.contains(&c_name) {
                    claimed_c.insert(c_name.clone());
                    Is::There
                } else {
                    Is::Missing
                }
            } else if !c_name.is_empty()
                && t.c_struct.as_ref().is_some_and(|st| c.structs.get(st).is_some_and(|f| f.contains(&c_name)))
            {
                Is::There
            } else {
                Is::Missing
            };
            e.rows.push(Row {
                key: (ty.clone(), it.name.clone()),
                class: class.clone(),
                says: s,
                py_name,
                c_name,
                py: py_is,
                c: c_is,
            });
        }
    }
    for k in types.keys() {
        if !rust.types.contains_key(k) || rust_only_module(k) {
            e.stale.push(format!("{MANIFEST}: types.{k:?}: no such type with something to bind"));
        }
    }
    for it in rust.items.iter().filter(|i| !rust.types.contains_key(&i.owner)) {
        let path = format!("{}::{}", it.owner, it.name);
        if rust_only_module(&path) {
            continue;
        }
        let s = says(functions.get(&path)).map_err(|x| format!("{MANIFEST}: functions.{path:?}: {x}"))?;
        let py_name = s.py.clone().unwrap_or_else(|| it.name.clone());
        let py_is = if s.rust_only.is_some() || py_name == "-" {
            Is::NotBound
        } else if py.get("").is_some_and(|m| m.contains(&py_name)) {
            claimed_py.insert((String::new(), py_name.clone()));
            Is::There
        } else {
            Is::Missing
        };
        let c_name = s.c.clone().unwrap_or_else(|| format!("fs_inspect_{}", it.name));
        let c_is = if s.rust_only.is_some() || not_bound(&c_name) {
            Is::NotBound
        } else if c.functions.contains(&c_name) {
            claimed_c.insert(c_name.clone());
            Is::There
        } else {
            Is::Missing
        };
        e.rows.push(Row {
            key: (String::new(), path),
            class: String::new(),
            says: s,
            py_name,
            c_name,
            py: py_is,
            c: c_is,
        });
    }
    for k in functions.keys() {
        let known =
            rust.items.iter().any(|i| !rust.types.contains_key(&i.owner) && format!("{}::{}", i.owner, i.name) == *k);
        if !known {
            e.stale.push(format!("{MANIFEST}: functions.{k:?}: no such function"));
        }
    }
    for (class, members) in &py {
        if !class.is_empty() && !claimed_py.contains(&(class.clone(), String::new())) {
            e.leftover_py.insert(class.clone());
            continue;
        }
        for mbr in members.iter().filter(|m| !m.starts_with('_')) {
            if !claimed_py.contains(&(class.clone(), mbr.clone())) {
                e.leftover_py.insert(if class.is_empty() { mbr.clone() } else { format!("{class}.{mbr}") });
            }
        }
    }
    e.leftover_c = c.functions.iter().filter(|f| !claimed_c.contains(*f)).cloned().collect();
    e.manifest = m;
    Ok(e)
}

/// What `lint` reports.
#[derive(Debug, Default)]
pub struct Report {
    pub problems: Vec<String>,
    pub pending_py: usize,
    pub pending_c: usize,
    pub strict: bool,
}

/// A leftover's reason that is still to be written.
const TODO: &str = "TODO";

/// A C name that says the item is not bound there: `"-"`, or `"- why"` with the reason.
fn not_bound(c_name: &str) -> bool {
    c_name.starts_with('-')
}

/// The problems, and how many items are pending (Python, C).
pub fn check(api: &str, pyi: &str, kinds: &str, header: &str, manifest: &str) -> Result<Report, String> {
    let e = evaluate(api, pyi, kinds, header, manifest)?;
    let mut r = Report {
        strict: e.manifest.get("strict").and_then(Value::as_bool).unwrap_or(false),
        problems: e.stale.clone(),
        ..Report::default()
    };
    let mut type_pending_py: BTreeSet<&str> = BTreeSet::new();
    for row in &e.rows {
        let (ty, item) = (&row.key.0, &row.key.1);
        let what = match (ty.is_empty(), item.is_empty()) {
            (true, _) => item.clone(),
            (false, true) => ty.clone(),
            (false, false) => format!("{ty}::{item}"),
        };
        if !ty.is_empty() && item.is_empty() && row.says.pending_py {
            type_pending_py.insert(ty);
        }
        let pending_py = row.says.pending_py || type_pending_py.contains(ty.as_str());
        match (row.py, pending_py) {
            (Is::Missing, true) => r.pending_py += 1,
            (Is::Missing, false) => r.problems.push(format!("py: no {} ({what})", py_place(row))),
            (Is::There, true) if row.says.pending_py => {
                r.problems.push(format!("py: {} is there: not pending ({what})", py_place(row)))
            }
            _ => {}
        }
        match (row.c, row.says.pending_c) {
            (Is::Missing, true) => r.pending_c += 1,
            (Is::Missing, false) if row.c_name.is_empty() => r.problems.push(format!("c: no C name ({what})")),
            (Is::Missing, false) => r.problems.push(format!("c: no {} ({what})", row.c_name)),
            (Is::There, true) => r.problems.push(format!("c: {} is there: not pending ({what})", row.c_name)),
            _ => {}
        }
    }
    let empty = Table::new();
    let tbl = |k: &str| e.manifest.get(k).and_then(Value::as_table).unwrap_or(&empty);
    for (side, left, extra, count) in [
        ("py", &e.leftover_py, tbl("python-extra"), &mut r.pending_py),
        ("c", &e.leftover_c, tbl("c-extra"), &mut r.pending_c),
    ] {
        for k in left {
            match extra.get(k).and_then(Value::as_str) {
                Some(TODO) => *count += 1,
                Some(why) if !why.is_empty() => {}
                _ => r.problems.push(format!("{side}: {k} binds no Rust item (say why in the extras)")),
            }
        }
        for k in extra.keys() {
            if !left.contains(k) {
                r.problems.push(format!("{MANIFEST}: extra {k}: binds a Rust item, or is not there"));
            }
        }
    }
    Ok(r)
}

/// The methods of the stub that take no argument and yet are no property: each reads, blocks,
/// changes something or makes something new. Any other such `def` is a property to be.
const NO_ARG_METHODS: [&str; 7] = [
    "CancelToken.cancel",
    "CancelToken.check",
    "CancelToken.child",
    "DiskSpec.raw",
    "Name.escape",
    "ReadAhead.clear",
    "Timestamp.to_datetime",
];

/// The classes of the stub that hold something open: each has `close()`, and `__enter__` with
/// an `__exit__` returning `None`.
const HANDLES: [&str; 11] = [
    "BlockSource",
    "Device",
    "DirCursor",
    "DirSink",
    "DiskSet",
    "Fs",
    "ReadAhead",
    "TarSink",
    "Volume",
    "Walker",
    "ZipSink",
];

/// The binding's rules for the stub and the async module: a `def` of no argument is a method
/// of [`NO_ARG_METHODS`] (else a property); each of [`HANDLES`] closes, an `__exit__` returns
/// `None`; an async class has `aclose()` (when its class closes) and never `close()`.
pub fn stub_rules(pyi: &str, aio: &str) -> Vec<String> {
    let mut problems = Vec::new();
    let classes = crate::aio_gen::parse(pyi);
    for c in &classes {
        for m in &c.methods {
            let only_self = m.params.iter().all(|p| p == "self");
            let closing = m.name == "close" && HANDLES.contains(&c.name.as_str());
            if !m.property && !m.static_ && only_self && !m.name.starts_with("__") && !closing {
                let name = format!("{}.{}", c.name, m.name);
                if !NO_ARG_METHODS.contains(&name.as_str()) {
                    problems
                        .push(format!("stub: {name}() takes no argument: a property, or a method of NO_ARG_METHODS"));
                }
            }
            if m.name == "__exit__" && m.ret != "None" {
                problems.push(format!("stub: {}.__exit__ returns None", c.name));
            }
        }
        if HANDLES.contains(&c.name.as_str()) {
            for need in ["close", "__enter__", "__exit__"] {
                if !c.methods.iter().any(|m| m.name == need) {
                    problems.push(format!("stub: the handle {} has no {need}", c.name));
                }
            }
        }
    }
    for h in HANDLES {
        if !classes.iter().any(|c| c.name == h) {
            problems.push(format!("stub: no handle {h}"));
        }
    }
    let closes = |name: &str| classes.iter().any(|c| c.name == name && c.methods.iter().any(|m| m.name == "close"));
    for (class, members) in async_classes(aio) {
        if members.iter().any(|m| m == "close") {
            problems.push(format!("aio: {class} has close(); an async class has aclose() only"));
        }
        let sync = class.trim_start_matches("Async");
        if closes(sync) && !members.iter().any(|m| m == "aclose") {
            problems.push(format!("aio: {class} has no aclose(), and {sync} closes"));
        }
    }
    problems
}

/// Each top-level class of the async module, with the names it defines (`def` or `async def`).
fn async_classes(aio: &str) -> Vec<(String, Vec<String>)> {
    let mut out: Vec<(String, Vec<String>)> = Vec::new();
    for line in aio.lines() {
        if let Some(rest) = line.strip_prefix("class ") {
            out.push((rest.split(['(', ':']).next().unwrap_or("").trim().to_string(), Vec::new()));
        } else if let Some(def) = line.strip_prefix("    def ").or_else(|| line.strip_prefix("    async def "))
            && let Some((_, members)) = out.last_mut()
        {
            members.push(def.split('(').next().unwrap_or("").to_string());
        } else if !line.is_empty() && !line.starts_with(' ') && !line.starts_with('#') && !line.starts_with(')') {
            // Module-level code ends the class.
            if !line.starts_with("class ") && !line.starts_with('@') {
                out.push((String::new(), Vec::new()));
            }
        }
    }
    out.retain(|(c, _)| c.starts_with("Async"));
    out
}

/// `Class.member`, `Class` or `function`, as the row looks for it.
fn py_place(row: &Row) -> String {
    match (row.key.0.is_empty(), row.key.1.is_empty()) {
        (false, true) => format!("class {}", row.py_name),
        (true, _) => format!("function {}", row.py_name),
        (false, false) => format!("{}.{}", row.class, row.py_name),
    }
}

fn read(rel: &str) -> Result<String, String> {
    std::fs::read_to_string(root().join(rel)).map_err(|e| format!("{rel}: {e}"))
}

fn inputs() -> Result<[String; 4], String> {
    let mut kinds = String::new();
    for k in KINDS {
        kinds.push_str(&read(k)?);
        kinds.push('\n');
    }
    Ok([read(API)?, read(STUB)?, kinds, read(HEADER)?])
}

/// `lint`'s step: no problem, and nothing pending once the manifest is strict.
pub fn ok() -> bool {
    step(&format!("parity of the Rust, Python and C APIs ({MANIFEST})"));
    let run = || -> Result<Report, String> {
        let [api, pyi, kinds, h] = inputs()?;
        let mut r = check(&api, &pyi, &kinds, &h, &read(MANIFEST)?)?;
        r.problems.extend(stub_rules(&pyi.replace("\r\n", "\n"), &read(AIO)?.replace("\r\n", "\n")));
        Ok(r)
    };
    match run() {
        Ok(r) => {
            for p in &r.problems {
                eprintln!("  {p}");
            }
            let pending = r.pending_py + r.pending_c;
            if pending > 0 {
                eprintln!("  pending: {} in Python, {} in C", r.pending_py, r.pending_c);
            }
            r.problems.is_empty() && (!r.strict || pending == 0)
                || fail(format!("parity: {} problem(s), {pending} pending", r.problems.len()))
        }
        Err(e) => fail(format!("parity: {e}")),
    }
}

/// The manifest as `gen parity` writes it now.
fn updated() -> Result<String, String> {
    let [api, pyi, kinds, h] = inputs()?;
    let m = std::fs::read_to_string(root().join(MANIFEST)).unwrap_or_default();
    update_text(&api, &pyi, &kinds, &h, &m)
}

/// Whether the manifest is what `gen parity` writes (its pending marks and leftovers current).
pub fn current() -> bool {
    step(&format!("{MANIFEST} up to date"));
    match (updated(), read(MANIFEST)) {
        (Ok(fresh), Ok(old)) if crate::generate::same(&old, &fresh) => true,
        (Ok(_), Ok(_)) => crate::generate::stale(MANIFEST, "parity"),
        (Err(e), _) | (_, Err(e)) => fail(format!("parity: {e}")),
    }
}

/// `gen parity`: the manifest rewritten ([`update_text`]).
pub fn write() -> bool {
    step(&format!("generate {MANIFEST}"));
    match updated().and_then(|t| std::fs::write(root().join(MANIFEST), t).map_err(|e| format!("{MANIFEST}: {e}"))) {
        Ok(()) => true,
        Err(e) => fail(format!("parity: {e}")),
    }
}

/// The manifest rewritten: its names, reasons and module list kept, `pending` set to what each
/// binding lacks, entries of items that are gone dropped, every leftover listed (its reason
/// kept, a new one `TODO`). What `gen parity` writes after a binding gained or lost something.
pub fn update_text(api: &str, pyi: &str, kinds: &str, header: &str, manifest: &str) -> Result<String, String> {
    let e = evaluate(api, pyi, kinds, header, manifest)?;
    let empty = Table::new();
    let tbl = |k: &str| e.manifest.get(k).and_then(Value::as_table).unwrap_or(&empty);
    let mut s = String::from(HEAD);
    if e.manifest.get("strict").and_then(Value::as_bool) == Some(true) {
        s.push_str("strict = true\n");
    }
    s.push_str("\n[modules]\n");
    for (k, v) in tbl("modules") {
        let _ = writeln!(s, "{} = {}", key(k), q(v.as_str().unwrap_or(TODO)));
    }
    let mut functions = String::new();
    let mut section: Option<(String, Vec<String>, Vec<String>)> = None;
    let flush = |s: &mut String, sec: &mut Option<(String, Vec<String>, Vec<String>)>| {
        if let Some((ty, head, items)) = sec.take()
            && !(head.is_empty() && items.is_empty())
        {
            let _ = writeln!(s, "\n[types.{}]", q(&ty));
            for l in head.iter().chain(&items) {
                let _ = writeln!(s, "{l}");
            }
        }
    };
    let mut class_missing = false;
    for row in &e.rows {
        let (ty, item) = (&row.key.0, &row.key.1);
        let d = &row.says;
        if ty.is_empty() {
            let mut f = fields(d, row.py == Is::Missing, row.c == Is::Missing);
            if !f.is_empty() {
                f.sort_by_key(|x| !x.starts_with("rust-only"));
                let _ = writeln!(functions, "{} = {{ {} }}", q(item), f.join(", "));
            }
            continue;
        }
        if item.is_empty() {
            flush(&mut s, &mut section);
            class_missing = row.py == Is::Missing;
            let mut head = Vec::new();
            for (k, v) in [("py", &d.py), ("c", &d.c), ("c-struct", &d.c_struct), ("rust-only", &d.rust_only)] {
                if let Some(v) = v {
                    head.push(format!("{k} = {}", q(v)));
                }
            }
            if class_missing {
                head.push("pending = [\"py\"]".into());
            }
            section = Some((ty.clone(), head, Vec::new()));
            continue;
        }
        let f = fields(d, row.py == Is::Missing && !class_missing, row.c == Is::Missing);
        if let Some((_, _, items)) = &mut section
            && !f.is_empty()
        {
            items.push(format!("items.{} = {{ {} }}", key(item), f.join(", ")));
        }
    }
    flush(&mut s, &mut section);
    let _ = write!(s, "\n[functions]\n{functions}");
    for (title, left, extra) in
        [("python-extra", &e.leftover_py, tbl("python-extra")), ("c-extra", &e.leftover_c, tbl("c-extra"))]
    {
        let _ = writeln!(s, "\n[{title}]");
        for k in left {
            let why = extra.get(k).and_then(Value::as_str).filter(|w| !w.is_empty()).unwrap_or(TODO);
            let _ = writeln!(s, "{} = {}", key(k), q(why));
        }
    }
    Ok(s)
}

/// An entry's `key = value`s: its names and reason as the manifest says, `pending` as found.
fn fields(d: &Says, py_missing: bool, c_missing: bool) -> Vec<String> {
    let mut f = Vec::new();
    for (k, v) in [("py", &d.py), ("c", &d.c), ("rust-only", &d.rust_only)] {
        if let Some(v) = v {
            f.push(format!("{k} = {}", q(v)));
        }
    }
    let pending: Vec<&str> =
        [("\"py\"", py_missing), ("\"c\"", c_missing)].into_iter().filter(|(_, m)| *m).map(|(p, _)| p).collect();
    if !pending.is_empty() && d.rust_only.is_none() {
        f.push(format!("pending = [{}]", pending.join(", ")));
    }
    f
}

/// A TOML basic string.
fn q(s: &str) -> String {
    let mut o = String::from('"');
    for c in s.chars() {
        match c {
            '"' => o.push_str("\\\""),
            '\\' => o.push_str("\\\\"),
            c => o.push(c),
        }
    }
    o.push('"');
    o
}

/// A TOML key: bare when it can be.
fn key(s: &str) -> String {
    if !s.is_empty() && s.chars().all(|c| c.is_ascii_alphanumeric() || c == '_' || c == '-') {
        s.to_string()
    } else {
        q(s)
    }
}

const HEAD: &str = "\
# The facade's public items in the Python binding and the C API: `cargo xtask lint` checks both
# ways; `cargo xtask gen parity` rewrites this file, keeping its names and reasons and setting
# `pending` to what a binding lacks. Rules and defaults:
# crates/xtask/src/parity.rs.
#
#   [modules]               a module of Rust's only = why
#   [types.\"path\"]          py = class, c = function prefix, c-struct = struct,
#                           rust-only = why, pending = [\"py\"] (no class yet)
#   items.name = { py = .., c = .., rust-only = .., pending = [..] }   (\"-\" or \"- why\": not bound there)
#
# A Python \"-\" is bare: what Python leaves out is a Rust idiom its own protocols already give
# (a conversion, bits, an inner writer, an emptiness test: bytes, len(), an IntFlag), or a field
# its value holds another way, so the reason would be the same each time. A C \"- why\" says
# why, as what C leaves out differs item by item.
#   [functions]             \"path\" = { py = .., c = .., rust-only = .., pending = [..] }
#   [python-extra], [c-extra]   what binds no Rust item = why (\"TODO\": pending)
";

