"""fs-inspect for Python: read the file systems inside disk images, snapshot devices and backups.

Open disks as one set (``DiskSet.open``), list their volumes named as the guest systems
know them (``DiskSet.catalog``), browse a volume's file system (``Volume.browse``: ``Fs``),
read its files (``File``), map and verify its blocks (``Volume.map``, ``Volume.verify``).
Calls that read release the GIL while they run; a caller's ``Source`` is called from
fs-inspect's own threads. ``fs_inspect.aio`` has the same API for asyncio.

The names are the library's: classes, methods and fields alike. An enum is a ``StrEnum``
whose members equal their stable lower-case names (``stat.kind == NodeKind.FILE``); flags
are ``IntFlag``s. A value with variants (``LinkTarget``, ``VolumeState``, ...) has a class
per variant nested in it (``LinkTarget.Symlink``), each with its own fields and a ``kind``,
to take apart with ``match``. Values compare and hash by their fields; options also have
``replace(**changes)``. Each ``ErrorKind`` has its exception, a subclass of
``FsInspectError`` and, where one means the same, of a built-in one (``NotFoundError`` is a
``FileNotFoundError``).

``File``, ``DirCursor``, ``Walker`` and ``ReadAhead`` are context managers; ``Listing``,
``Siblings`` and ``Blocks`` are ``Sequence``s.

Generated by ``cargo xtask gen bindings``: do not edit.
"""

