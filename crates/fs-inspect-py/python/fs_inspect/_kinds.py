class FsKind(StrEnum):
    """File system kind."""

    #: NTFS.
    NTFS = "ntfs"
    #: FAT12.
    FAT12 = "fat12"
    #: FAT16.
    FAT16 = "fat16"
    #: FAT32.
    FAT32 = "fat32"
    #: exFAT.
    EXFAT = "exfat"
    #: ext2.
    EXT2 = "ext2"
    #: ext3 (ext2 with a journal).
    EXT3 = "ext3"
    #: ext4.
    EXT4 = "ext4"
    #: XFS.
    XFS = "xfs"
    #: Btrfs.
    BTRFS = "btrfs"
    #: APFS: a container.
    APFS = "apfs"
    #: ReFS.
    REFS = "refs"
    #: A ZFS leaf vdev (a disk, a file, a mirror leg or a raidz child of a pool without dRAID), or a
    #: cache or spare device.
    ZFS = "zfs"
    #: No file system recognized (BIOS boot, MSR, LVM, encrypted, ...): the whole partition is
