class DiskProblem(StrEnum):
    """Disk problem."""

    #: Its structures are damaged (a partition table or a file system that does not read as one).
    DAMAGED = "damaged"
    #: The source does not have bytes it needs (``DataMissing``).
    DATA_MISSING = "data_missing"
    #: It uses a feature fs-inspect does not read.
    UNSUPPORTED = "unsupported"
    #: A logical volume, or a volume on one, whose container lacks members (``Unavailable``): giving
