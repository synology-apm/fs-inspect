"""The kinds and flags of fs-inspect: every enum a caller sees, each value a ``StrEnum`` member
equal to its stable name (``stat.kind == "file"``), and the flags as ``IntFlag``.

Generated by ``cargo xtask gen bindings`` from the library's registry: do not edit.
"""

from __future__ import annotations

