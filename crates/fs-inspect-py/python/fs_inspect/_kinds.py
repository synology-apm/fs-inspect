class Want(IntFlag):
    """What a node's info holds besides its name (``Fs.info``, ``DirOptions.want``,
    ``WalkOptions.want``): ``NONE``, names only; ``STAT``, the stat alone; another facet reads the
    stat too.
    """

    #: No info: names only.
    NONE = 0x0
    #: The stat.
    STAT = 0x40
    #: A link's or reparse point's target.
    LINK = 0x4
    #: Every name of the node (its hard links).
    NAMES = 0x10
    #: Its access control.
    SECURITY = 0x2
    #: Its data streams.
    STREAMS = 0x8
    #: Its extended attributes.
    XATTRS = 0x1
    #: Every facet.
    ALL = 0x5f

    def contains(self, other: Self) -> bool:
        """Whether every facet of ``other`` is wanted."""
        return self & other == other

    @property
    def info(self) -> Want | None:
        """The facets to read when any info is wanted, ``None`` for ``NONE``."""
        return None if self == 0 else Want(self & ~Want.STAT)

    def without(self, other: Want) -> Want:
        """These facets without those of ``other``."""
        return Want(self & ~other)


class MetaFacets(IntFlag):
    """Which of a node's metadata ``Fs.restore_metadata`` writes onto a host file. A facet the node has
    but the host cannot represent for it is skipped as unsupported; one the node does not have is
    nothing to write.
    """

    #: No facet.
    NONE = 0x0
    #: The modification and access times (and the creation time on Windows); a link's own.
    TIMES = 0x1
    #: The Unix permission bits on a Unix host; the read-only, hidden, system, archive and
    #: not-indexed attributes on Windows. A node with only the other kind is unsupported. A symbolic
    #: link's own bits are set on macOS and the BSDs; a Linux link has none: nothing to write.
    MODE = 0x2
    #: The owner and group: a Unix node's on a Unix host (giving a file away needs root), a Windows
